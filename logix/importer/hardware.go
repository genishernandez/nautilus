package importer

import (
	"strings"

	"github.com/joyautomation/nautilus/lang/l5x"
)

// HardwareFile is where an import keeps the export's I/O configuration,
// relative to the project: target.logix.hardware names it, and the
// writer carries its <Modules> into every project it writes (#275).
const HardwareFile = "hardware.L5X"

// hardwareFile is the hardware configuration of an export with I/O: an
// L5X holding the controller's identity and the export's <Modules>
// element, its contents as the export has them (line ends made LF, which
// XML reads the same). nil for an export whose only module is the
// controller's own Local module, which the writer generates from the
// processor; and for one with no <Modules> at all (a partial export).
func hardwareFile(f *l5x.File) []byte {
	c := f.Controller
	if c == nil || strings.TrimSpace(c.ModulesXML) == "" {
		return nil
	}
	io := false
	for _, m := range c.Modules {
		if m.Name != "Local" {
			io = true
		}
	}
	if !io {
		return nil
	}
	sw := f.SoftwareRevision
	if sw == "" {
		sw = "38.01"
	}
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` + "\n")
	b.WriteString("<!-- Generated by `naut logix import` from the " + xmlComment(c.Name) + " export: the controller's\n")
	b.WriteString("     I/O configuration, the export's <Modules> section unchanged. nautilus\n")
	b.WriteString("     writes it into every project it builds (target.logix.hardware), so\n")
	b.WriteString("     the alias tags have their modules. To change the hardware, change it\n")
	b.WriteString("     in Logix Designer and export the project over this file, or re-run\n")
	b.WriteString("     the import; any whole-project export works as it is. -->\n")
	b.WriteString(`<RSLogix5000Content SchemaRevision="1.0" SoftwareRevision="` + xmlAttr(sw) + `" TargetName="` + xmlAttr(c.Name) + `" TargetType="Controller" ContainsContext="false">` + "\n")
	b.WriteString(`<Controller Use="Target" Name="` + xmlAttr(c.Name) + `" ProcessorType="` + xmlAttr(c.ProcessorType) + `" MajorRev="` + xmlAttr(c.MajorRev) + `" MinorRev="` + xmlAttr(c.MinorRev) + `">` + "\n")
	b.WriteString(strings.ReplaceAll(strings.TrimSpace(c.ModulesXML), "\r\n", "\n") + "\n")
	b.WriteString("</Controller>\n</RSLogix5000Content>\n")
	return []byte(b.String())
}

func xmlAttr(s string) string {
	return strings.NewReplacer(`&`, "&amp;", `<`, "&lt;", `>`, "&gt;", `"`, "&quot;").Replace(s)
}

// xmlComment keeps a name from closing the comment it sits in.
func xmlComment(s string) string { return strings.ReplaceAll(s, "--", "- -") }
